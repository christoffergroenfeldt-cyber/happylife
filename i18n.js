let current = 'da';
export function setLang(l) { if (STRINGS[l]) current = l; document.documentElement.lang = current; }
export function getLang() { return current; }

// t('hello', {name}) ; t('daysAgo', 3) ; t('roles.husband')
export function t(key, arg) {
  const v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), STRINGS[current]) ??
            key.split('.').reduce((o, k) => (o == null ? o : o[k]), STRINGS.en) ?? key;
  if (typeof v === 'function') return v(arg);
  if (arg && typeof arg === 'object' && typeof v === 'string')
    return v.replace(/\{(\w+)\}/g, (_, k) => arg[k] ?? '');
  return v;
}
